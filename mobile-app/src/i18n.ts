export function getLocalizedText(value: LocalizedText, language: Language) {
  return value[language] || value.en;
}

export function translateRegion(region: Region, language: Language) {
  return getLocalizedText(regionLabels[region], language);
}

export function translateCategory(category: Category, language: Language) {
  return getLocalizedText(categoryLabels[category], language);
}
